"""Expand metadata.public_spec into a discriminating CGVL coverage matrix.

Slots are generated by the harness from signatures and clause text. The agent
does not invent clauses. Never copy source_entrypoints or evaluator tests.
"""

from __future__ import annotations

import re
from typing import Any

from .common import SCHEMA_VERSION

_QUOTE_STRIP = re.compile(r"^['\"]|['\"]$")
_STATE_RE = re.compile(
    r"\b(unregister|only matching|matching value|must not|does not change|"
    r"no side effect|invariant|still remain|without (?:changing|removing))\b",
    re.IGNORECASE,
)
_AMBIGUITY_RE = re.compile(
    r"\b(abbreviation|placeholder|bound arguments?|call order|"
    r"primitive types?|schema text)\b",
    re.IGNORECASE,
)
# Explicit co-occurring dimensions from the failure audit. Do not split every "and".
_PAIR_DIMS = (
    {
        "left": ("quoted-value", "quoted value", "quotes comments"),
        "right": ("comment",),
        "path_hints": ("repositoryenv", "repository_env", "config"),
        "label": "quote AND comment",
    },
    {
        "left": ("alias",),
        "right": ("load_zone", "load zone"),
        "path_hints": ("load_zone", "gettz", "get"),
        "label": "alias AND load_zone",
    },
    {
        "left": ("brace",),
        "right": ("factor",),
        "path_hints": ("find_envs", "expand_factors", "filter_for_env"),
        "label": "brace AND factor",
    },
)
_SKIP_KINDS = frozenset({"exception", "isolation"})
_ENV_PLATFORM_NAMES = frozenset(
    {"platform", "env", "environ", "home", "sys_prefix", "user_site_base"}
)
_CALLABLE_KINDS = frozenset(
    {
        "callable",
        "class",
        "classmethod",
        "constructor",
        "function",
        "method",
        "staticmethod",
    }
)
_API_SURFACE_RE = re.compile(
    r"\b(?:package )?exposes?\b.*\b(?:api paths?|callable signatures?|kinds)\b",
    re.IGNORECASE,
)


def _clean_type(raw: str) -> str:
    text = str(raw or "").strip()
    text = text.replace('"', "'")
    while text.startswith("'") or text.endswith("'"):
        text = _QUOTE_STRIP.sub("", text).strip()
    return re.sub(r"\s+", " ", text)


def _split_top_level(text: str, separator: str) -> list[str]:
    """Split on separator that is outside quotes and brackets."""

    parts: list[str] = []
    buf: list[str] = []
    depth = 0
    quote = ""
    index = 0
    sep_len = len(separator)
    while index < len(text):
        char = text[index]
        if quote:
            buf.append(char)
            if char == quote:
                quote = ""
            index += 1
            continue
        if char in {"'", '"'}:
            quote = char
            buf.append(char)
            index += 1
            continue
        if char in "[(":
            depth += 1
            buf.append(char)
            index += 1
            continue
        if char in "])":
            depth = max(0, depth - 1)
            buf.append(char)
            index += 1
            continue
        if depth == 0 and text.startswith(separator, index):
            part = "".join(buf).strip()
            if part:
                parts.append(part)
            buf = []
            index += sep_len
            continue
        buf.append(char)
        index += 1
    part = "".join(buf).strip()
    if part:
        parts.append(part)
    return parts


def _split_union(type_text: str) -> list[str]:
    cleaned = _clean_type(type_text)
    if not cleaned:
        return []
    parts = [_clean_type(part) for part in _split_top_level(cleaned, "|") if _clean_type(part)]
    return parts if len(parts) >= 2 else []


def _split_name_type_default(part: str) -> tuple[str, str, str]:
    name_end: int | None = None
    default_at: int | None = None
    depth = 0
    quote = ""
    for index, char in enumerate(part):
        if quote:
            if char == quote:
                quote = ""
            continue
        if char in {"'", '"'}:
            quote = char
            continue
        if char in "[(":
            depth += 1
            continue
        if char in "])":
            depth = max(0, depth - 1)
            continue
        if depth != 0:
            continue
        if char == ":" and name_end is None:
            name_end = index
        elif char == "=" and default_at is None:
            default_at = index
    if name_end is None:
        name = part[: default_at if default_at is not None else len(part)].strip()
        type_text = ""
    else:
        name = part[:name_end].strip()
        type_end = default_at if default_at is not None else len(part)
        type_text = part[name_end + 1 : type_end].strip()
    default = part[default_at + 1 :].strip() if default_at is not None else ""
    return name, _clean_type(type_text), default


def _parse_params(signature: str) -> list[dict[str, str]]:
    sig = str(signature or "").strip()
    if sig.startswith("(") and ")" in sig:
        sig = sig[1 : sig.rfind(")")]
    params: list[dict[str, str]] = []
    for part in _split_top_level(sig, ","):
        name, type_text, default = _split_name_type_default(part)
        if not name or name in {"self", "cls"} or name.startswith("*"):
            continue
        params.append({"name": name, "type": type_text, "default": default})
    return params


def _preferred_entry(api_rows: list[dict[str, Any]], tokens: list[str]) -> str:
    lowered = [token.lower() for token in tokens if token]
    for token in lowered:
        for row in api_rows:
            kind = str(row.get("kind") or "")
            path = str(row.get("path") or "")
            if not path or kind in _SKIP_KINDS:
                continue
            if token not in path.lower():
                continue
            if _symbol_name(path) == "__init__":
                return path.rsplit(".", 1)[0]
            return path
    for row in api_rows:
        path = str(row.get("path") or "")
        if path and str(row.get("kind") or "") not in _SKIP_KINDS:
            if _symbol_name(path) == "__init__":
                return path.rsplit(".", 1)[0]
            return path
    return ""


def flatten_required_api(public_spec: dict[str, Any]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    required = public_spec.get("required_api")
    if not isinstance(required, list):
        return rows

    def visit(entry: Any, *, member: bool) -> None:
        if not isinstance(entry, dict):
            return
        path = str(entry.get("path") or "").strip()
        if not path:
            return
        rows.append(
            {
                "path": path,
                "kind": str(entry.get("kind") or "").strip() or "symbol",
                "signature": str(entry.get("signature") or "").strip(),
                "member": member,
            }
        )
        members = entry.get("members")
        if not isinstance(members, list):
            return
        for child in members:
            visit(child, member=True)

    for entry in required:
        visit(entry, member=False)
    return rows


def _symbol_name(path: str) -> str:
    return path.rsplit(".", 1)[-1]


def _mutants_for(role: str) -> list[str]:
    mapping = {
        "entry": ["helper_only_probe", "wrong_public_entry"],
        "variant": ["drop_union_arm", "treat_class_as_instance"],
        "pairwise": ["test_conjuncts_separately"],
        "state_guard": ["ignore_mismatch_value", "skip_failed_op_noop"],
        "negative": ["skip_declared_exception"],
        "parameter": ["use_host_platform_rules"],
        "oracle": ["weak_concat_oracle"],
        "behavior": ["wrong_behavior_oracle"],
        "lifecycle": ["constructor_only_coverage", "skip_state_transition"],
    }
    return list(mapping.get(role, []))


def _cell(
    *,
    cell_id: str,
    clause: str,
    public_entry: str,
    role: str,
    input_variant: str = "",
    positive: str = "",
    negative: str = "",
    state_invariant: str = "",
    required: bool = True,
    undetermined: bool = False,
    behavior_id: str = "",
    expected_exception: str = "",
    public_entries: list[str] | None = None,
    required_variants: list[str] | None = None,
    min_assertions: int = 1,
    min_public_entries: int = 1,
) -> dict[str, Any]:
    entries = [str(item) for item in (public_entries or []) if str(item)]
    if public_entry and public_entry not in entries:
        entries.insert(0, public_entry)
    return {
        "id": cell_id,
        "clause": clause,
        "public_entry": public_entry,
        "role": role,
        "input_variant": input_variant,
        "positive_case": positive,
        "negative_case": negative,
        "state_invariant": state_invariant,
        "required_mutants": _mutants_for(role),
        "required": required and not undetermined,
        "undetermined": undetermined,
        "behavior_id": behavior_id,
        "expected_exception": expected_exception,
        "public_entries": entries,
        "required_variants": list(required_variants or []),
        "min_assertions": max(1, int(min_assertions)),
        "min_public_entries": max(1, int(min_public_entries)),
        "assertion_required": required and not undetermined,
        "verification_status": "pending",
    }


def _behavior_rows(public_spec: dict[str, Any]) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    raw = public_spec.get("behaviors")
    if not isinstance(raw, list):
        return rows
    for item in raw:
        if not isinstance(item, dict):
            continue
        behavior_id = str(item.get("id") or "").strip()
        text = str(item.get("text") or "").strip()
        if behavior_id and text:
            rows.append({"id": behavior_id, "text": text})
    return rows


def _exception_names(api_rows: list[dict[str, Any]]) -> list[str]:
    names: list[str] = []
    for row in api_rows:
        if str(row.get("kind") or "") != "exception":
            continue
        name = _symbol_name(str(row.get("path") or ""))
        if name:
            names.append(name)
    return names


def _callable_paths(api_rows: list[dict[str, Any]]) -> list[str]:
    """Return public callable paths; modules and attributes are import-checked only."""

    return [
        str(row.get("path") or "")
        for row in api_rows
        if str(row.get("kind") or "").lower() in _CALLABLE_KINDS
        and str(row.get("path") or "")
    ]


def _behavior_role(text: str) -> tuple[str, str]:
    """Choose one compact semantic row per public behavior clause."""

    lowered = text.lower()
    if _STATE_RE.search(text):
        return "state_guard", ""
    for pair in _PAIR_DIMS:
        if any(token in lowered for token in pair["left"]) and any(
            token in lowered for token in pair["right"]
        ):
            return "pairwise", str(pair["label"])
    if "token" in lowered and any(
        word in lowered for word in ("strip", "whitespace", "option")
    ):
        return "oracle", "token-type and option oracle"
    return "behavior", ""


def _behavior_public_entries(
    text: str,
    api_rows: list[dict[str, Any]],
) -> list[str]:
    """Rank callable entries by lexical relevance, retaining safe fallbacks.

    The matrix owns the candidate surface but does not guess one source symbol.
    The checker later verifies the exact public paths that the probe calls.
    """

    callable_rows = [
        row
        for row in api_rows
        if str(row.get("kind") or "").lower() in _CALLABLE_KINDS
    ]
    if not callable_rows:
        return []
    words = {
        item
        for item in re.findall(r"[a-z0-9]+", text.lower().replace("_", " "))
        if len(item) >= 3
    }
    scored: list[tuple[int, str]] = []
    for row in callable_rows:
        path = str(row.get("path") or "")
        symbol_words = {
            item
            for item in re.findall(
                r"[a-z0-9]+",
                re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", path).lower().replace("_", " "),
            )
            if len(item) >= 3 and item != "featurelifted"
        }
        scored.append((len(words & symbol_words), path))
    relevant = [path for score, path in scored if score > 0]
    if relevant:
        return relevant
    return [path for _, path in scored]


def build_cgvl_matrix(public_spec: dict[str, Any]) -> dict[str, Any]:
    """Return harness-owned coverage cells. Agent may fill tests, not invent rows."""

    api_rows = flatten_required_api(public_spec)
    behaviors = _behavior_rows(public_spec)
    exceptions = _exception_names(api_rows)
    cells: list[dict[str, Any]] = []
    seen_keys: set[tuple[str, ...]] = set()

    def add(cell: dict[str, Any]) -> None:
        cell_id = str(cell.get("id") or "")
        if not cell_id:
            return
        key = (
            str(cell.get("role") or ""),
            str(cell.get("public_entry") or ""),
            str(cell.get("input_variant") or ""),
            str(cell.get("behavior_id") or ""),
            str(cell.get("expected_exception") or ""),
            "U" if cell.get("undetermined") else "R",
        )
        if key in seen_keys:
            return
        seen_keys.add(key)
        cells.append(cell)

    index = 1
    for row in api_rows:
        path = str(row.get("path") or "")
        kind = str(row.get("kind") or "")
        if not path or kind in _SKIP_KINDS:
            continue
        symbol = _symbol_name(path)
        is_init = symbol == "__init__"
        entry_path = path.rsplit(".", 1)[0] if is_init else path
        if is_init:
            symbol = _symbol_name(entry_path)
        if (
            not is_init
            and not bool(row.get("member"))
            and kind.lower() in _CALLABLE_KINDS
        ):
            add(
                _cell(
                    cell_id=f"C{index:03d}_entry_{symbol}",
                    clause=f"Public entry {entry_path} must be exercised directly.",
                    public_entry=entry_path,
                    role="entry",
                    positive=f"Call {entry_path} on a legal input and observe a declared result.",
                )
            )
            index += 1

        for param in _parse_params(str(row.get("signature") or "")):
            is_env_platform = param["name"].lower() in _ENV_PLATFORM_NAMES or "platform" in param[
                "type"
            ].lower()
            unions = _split_union(param["type"])
            if unions and not is_env_platform:
                variants = [f"{param['name']}={arm}" for arm in unions]
                add(
                    _cell(
                        cell_id=f"C{index:03d}_variant_{symbol}_{param['name']}",
                        clause=(
                            f"{entry_path} parameter {param['name']} accepts every "
                            f"declared union arm: {', '.join(unions)}."
                        ),
                        public_entry=entry_path,
                        role="variant",
                        input_variant=" | ".join(variants),
                        positive=(
                            f"Call {entry_path} once for each declared {param['name']} arm."
                        ),
                        required_variants=variants,
                        min_assertions=len(variants),
                    )
                )
                index += 1
            # Cross-platform semantics belong to the explicit Bxxx behavior cell.
            # A signature-only row per env/home/platform parameter created dozens
            # of low-value cells in v1 and consumed the model's step budget.

        return_union = ""
        sig = str(row.get("signature") or "")
        if "->" in sig:
            return_union = _clean_type(sig.split("->", 1)[1])
        if "None" in return_union and "|" in return_union and not exceptions:
            add(
                _cell(
                    cell_id=f"C{index:03d}_undetermined_{symbol}_none_vs_error",
                    clause=(
                        f"{entry_path} returns {return_union}; TASK does not uniquely "
                        "choose None versus an exception."
                    ),
                    public_entry=entry_path,
                    role="negative",
                    undetermined=True,
                    negative="Do not guess an undeclared exception type.",
                )
            )
            index += 1

    normalized_behavior_blob = re.sub(
        r"[^a-z0-9]",
        "",
        " ".join(
            row["text"] for row in behaviors if not _API_SURFACE_RE.search(row["text"])
        ).lower(),
    )
    for row in api_rows:
        if str(row.get("kind") or "") != "exception":
            continue
        exc = str(row.get("path") or "")
        if _symbol_name(exc).lower() in normalized_behavior_blob:
            # The complete Bxxx row below carries the precise negative scenario.
            continue
        preferred = _preferred_entry(
            api_rows,
            [
                "__setitem__",
                "normalize",
                "validate",
                "unregister",
                "parse",
                "revisionmap",
                "config",
                "repository",
            ],
        )
        target = preferred or _preferred_entry(api_rows, [])
        if _symbol_name(str(target)) == "__init__":
            target = str(target).rsplit(".", 1)[0]
        add(
            _cell(
                cell_id=f"C{index:03d}_negative_{_symbol_name(exc)}",
                clause=f"Declared exception {exc} must be raised on an invalid public call.",
                public_entry=target,
                role="negative",
                negative=f"A public call through {target} raises {_symbol_name(exc)}.",
                expected_exception=_symbol_name(exc),
            )
        )
        index += 1

    for behavior in behaviors:
        text = behavior["text"]
        behavior_id = behavior["id"]
        lowered = text.lower()
        if _API_SURFACE_RE.search(text):
            # Required symbols are already checked mechanically by import surface.
            continue
        # Every functional Bxxx gets a closure row. Specialized pairwise,
        # state, or oracle rows below are additional discriminating witnesses,
        # never replacements for the complete behavior clause.
        if behavior_id:
            normalized_text = re.sub(r"[^a-z0-9]", "", lowered)
            mentioned_exception = next(
                (name for name in exceptions if name.lower() in normalized_text),
                "",
            )
            entries = _behavior_public_entries(text, api_rows)
            all_entries = _callable_paths(api_rows)
            add(
                _cell(
                    cell_id=f"C{index:03d}_behavior_{behavior_id}",
                    clause=text,
                    public_entry=entries[0] if entries else "",
                    public_entries=all_entries,
                    role="negative" if mentioned_exception else "behavior",
                    behavior_id=behavior_id,
                    expected_exception=mentioned_exception,
                    positive=(
                        "Build one executable scenario with explicit actual/expected "
                        "assertions for this whole behavior clause."
                    ),
                    negative=(
                        f"The scenario must observe {mentioned_exception}."
                        if mentioned_exception
                        else ""
                    ),
                    min_public_entries=min(2, len(entries)) if entries else 1,
                )
            )
            index += 1
        if "token" in lowered and any(
            word in lowered for word in ("strip", "whitespace", "option")
        ):
            token_entry = next(
                (
                    row["path"]
                    for row in api_rows
                    if _symbol_name(str(row.get("path") or "")).lower()
                    in {"lex", "pythonlexer"}
                ),
                next((row["path"] for row in api_rows if row.get("kind") not in _SKIP_KINDS), ""),
            )
            add(
                _cell(
                    cell_id=f"C{index:03d}_oracle_{behavior_id}",
                    clause=text,
                    public_entry=str(token_entry).replace(".__init__", ""),
                    public_entries=_behavior_public_entries(text, api_rows),
                    role="oracle",
                    behavior_id=behavior_id,
                    min_assertions=2,
                    positive=(
                        "Observe token types, not concatenated text, for the declared option."
                    ),
                )
            )
            index += 1
        if _STATE_RE.search(text):
            state_entry = next(
                (
                    row["path"]
                    for row in api_rows
                    if "unregister" in str(row.get("path") or "").lower()
                    or "run_event" in str(row.get("path") or "").lower()
                    or "get_revision" in str(row.get("path") or "").lower()
                ),
                next((row["path"] for row in api_rows if row.get("kind") not in _SKIP_KINDS), ""),
            )
            add(
                _cell(
                    cell_id=f"C{index:03d}_state_{behavior_id}",
                    clause=text,
                    public_entry=str(state_entry).replace(".__init__", ""),
                    public_entries=_behavior_public_entries(text, api_rows),
                    role="state_guard",
                    behavior_id=behavior_id,
                    min_assertions=2,
                    negative="A failing or mismatched operation must leave prior state unchanged.",
                    state_invariant="Failed mutations are no-ops on the public state.",
                )
            )
            index += 1
        for pair in _PAIR_DIMS:
            if any(token in lowered for token in pair["left"]) and any(
                token in lowered for token in pair["right"]
            ):
                pair_id = f"pair_{pair['left'][0]}_{pair['right'][0]}"
                pair_entry = _preferred_entry(api_rows, list(pair["path_hints"]))
                add(
                    _cell(
                        cell_id=f"C{index:03d}_pairwise_{pair_id}",
                        clause=text,
                        public_entry=str(pair_entry).replace(".__init__", ""),
                        public_entries=_behavior_public_entries(text, api_rows),
                        role="pairwise",
                        behavior_id=pair_id,
                        input_variant=str(pair["label"]),
                        min_assertions=2,
                        positive="One input must exhibit both conjuncts together, not separately.",
                    )
                )
                index += 1
        if _AMBIGUITY_RE.search(text):
            add(
                _cell(
                    cell_id=f"C{index:03d}_undetermined_{behavior_id}",
                    clause=text,
                    public_entry=next(
                        (
                            str(row["path"]).replace(".__init__", "")
                            for row in api_rows
                            if row.get("kind") not in _SKIP_KINDS
                        ),
                        "",
                    ),
                    role="entry",
                    behavior_id=behavior_id,
                    undetermined=True,
                    positive="If TASK plus repo cannot uniquely determine the oracle, mark undetermined.",
                )
            )
            index += 1

        load_paths = [
            str(row["path"])
            for row in api_rows
            if "load_zone" in str(row.get("path") or "")
        ]
        if "alias" in lowered and load_paths:
            add(
                _cell(
                    cell_id=f"C{index:03d}_pairwise_alias_load",
                    clause="Alias resolution must hold on load_zone, not only get.",
                    public_entry=load_paths[0],
                    public_entries=_behavior_public_entries(text, api_rows),
                    role="pairwise",
                    behavior_id=behavior_id,
                    input_variant="register_alias then load_zone(alias)",
                    min_assertions=2,
                    positive="After register_alias, load_zone(alias) follows the canonical zone.",
                )
            )
            index += 1

    isolation = public_spec.get("isolation_behavior")
    isolation_id = ""
    if isinstance(isolation, dict):
        isolation_id = str(isolation.get("id") or "")
    forbidden = (
        public_spec.get("forbidden")
        if isinstance(public_spec.get("forbidden"), dict)
        else {}
    )

    dumped = {
        "schema_version": SCHEMA_VERSION,
        "title": str(public_spec.get("title") or "").strip(),
        "summary": str(public_spec.get("summary") or "").strip(),
        "cells": cells,
        "required_api": api_rows,
        "behaviors": behaviors,
        "isolation_behavior_id": isolation_id,
        "forbidden_imports": [
            str(item)
            for item in (forbidden.get("imports") or [])
            if str(item).strip()
        ],
        "forbidden_paths": [
            str(item)
            for item in (forbidden.get("paths") or [])
            if str(item).strip()
        ],
        "gate": {
            "finish_requires_ok": True,
            "public_entry_required": True,
            "union_arms_required": True,
            "state_negative_required": True,
            "undetermined_must_not_guess": True,
            "assertions_required": True,
            "counterexample_required": True,
            "forbidden_imports_required": True,
        },
    }
    blob = str(dumped)
    if "source_entrypoints" in blob:
        dumped["required_api"] = [
            {k: v for k, v in row.items() if k != "source_entrypoints"}
            for row in api_rows
        ]
    return dumped


def required_cells(matrix: dict[str, Any]) -> list[dict[str, Any]]:
    return [
        cell
        for cell in matrix.get("cells") or []
        if isinstance(cell, dict) and cell.get("required")
    ]
